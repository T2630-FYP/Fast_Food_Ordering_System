// Escape database values before displaying them in the administrator page.
function admin_product_html($value)
{
	return htmlspecialchars((string)$value,ENT_QUOTES,"UTF-8");
}

// Store one result message and redirect to prevent duplicate form submissions.
function admin_product_redirect($type,$message,$location="admin_product.php")
{
	$_SESSION["admin_product_flash"] = array("type"=>$type,"message"=>$message);
	header("Location: ".$location,true,303);
	exit();
}

// Only remove image files generated by this page; bundled menu images are preserved.
function admin_product_remove_generated_image($stored_path)
{
	$normalised = str_replace("\\","/",trim((string)$stored_path));
	if(preg_match("#^image/product-[a-z0-9-]+-[a-f0-9]{16}\\.(?:jpg|png|webp)$#",$normalised)!==1)
	{
		return;
	}

	$absolute_path = __DIR__.DIRECTORY_SEPARATOR.str_replace("/",DIRECTORY_SEPARATOR,$normalised);
	$image_directory = realpath(__DIR__.DIRECTORY_SEPARATOR."image");
	$file_directory = realpath(dirname($absolute_path));
	if($image_directory!==false && $file_directory===$image_directory && is_file($absolute_path))
	{
		unlink($absolute_path);
	}
}

// Validate a real image upload and return its safe project-relative path.
function admin_product_store_upload($file,$product_id,$required)
{
	if(!is_array($file) || !isset($file["error"]) || (int)$file["error"]===UPLOAD_ERR_NO_FILE)
	{
		if($required)
		{
			throw new RuntimeException("Please choose a product image.");
		}
		return null;
	}

	if((int)$file["error"]!==UPLOAD_ERR_OK)
	{
		throw new RuntimeException("The product image could not be uploaded.");
	}
	if((int)$file["size"]<=0 || (int)$file["size"]>5*1024*1024)
	{
		throw new RuntimeException("The product image must be 5 MB or smaller.");
	}
	if(!is_uploaded_file($file["tmp_name"]))
	{
		throw new RuntimeException("The uploaded image is invalid.");
	}

	$allowed_extensions = array("jpg","jpeg","png","webp");
	$extension = strtolower(pathinfo((string)$file["name"],PATHINFO_EXTENSION));
	if(!in_array($extension,$allowed_extensions,true))
	{
		throw new RuntimeException("Only JPG, PNG or WebP product images are allowed.");
	}

	$finfo = finfo_open(FILEINFO_MIME_TYPE);
	$mime_type = $finfo ? finfo_file($finfo,$file["tmp_name"]) : false;
	if($finfo)
	{
		finfo_close($finfo);
	}
	$mime_extensions = array("image/jpeg"=>"jpg","image/png"=>"png","image/webp"=>"webp");
	if($mime_type===false || !isset($mime_extensions[$mime_type]))
	{
		throw new RuntimeException("The selected file is not a supported image.");
	}

	$image_size = getimagesize($file["tmp_name"]);
	if($image_size===false || $image_size[0]<100 || $image_size[1]<100 || $image_size[0]>6000 || $image_size[1]>6000)
	{
		throw new RuntimeException("The product image dimensions must be between 100 and 6000 pixels.");
	}

	$image_directory = __DIR__.DIRECTORY_SEPARATOR."image";
	if(!is_dir($image_directory) || !is_writable($image_directory))
	{
		throw new RuntimeException("The image folder is not available for uploads.");
	}

	$safe_id = strtolower(preg_replace("/[^A-Za-z0-9]+/","-",$product_id));
	$safe_id = trim($safe_id,"-");
	if($safe_id==="")
	{
		$safe_id = "item";
	}
	$filename = "product-".$safe_id."-".bin2hex(random_bytes(8)).".".$mime_extensions[$mime_type];
	$absolute_path = $image_directory.DIRECTORY_SEPARATOR.$filename;
	if(!move_uploaded_file($file["tmp_name"],$absolute_path))
	{
		throw new RuntimeException("The product image could not be saved.");
	}

	return "image/".$filename;
}

// Process product changes only through validated POST requests.
if($_SERVER["REQUEST_METHOD"]==="POST")
{
	$submitted_token = (string)($_POST["csrf_token"] ?? "");
	if(!hash_equals($csrf_token,$submitted_token))
	{
		admin_product_redirect("error","The request expired. Please try again.");
	}

	$action = (string)($_POST["action"] ?? "");
	if($action==="save_product")
	{
		$mode = (string)($_POST["mode"] ?? "add");
		$product_id = strtoupper(trim((string)($_POST["product_id"] ?? "")));
		$product_name = trim((string)($_POST["product_name"] ?? ""));
		$product_desc = trim((string)($_POST["product_desc"] ?? ""));
		$product_category = trim((string)($_POST["product_category"] ?? ""));
		$product_price = filter_var($_POST["product_price"] ?? null,FILTER_VALIDATE_FLOAT);
		$product_stock = filter_var($_POST["product_stock"] ?? null,FILTER_VALIDATE_INT,array("options"=>array("min_range"=>0,"max_range"=>9999)));
		$product_status = trim((string)($_POST["product_status"] ?? ""));

		if(!in_array($mode,array("add","update"),true) || preg_match("/^[A-Z0-9]{1,5}$/",$product_id)!==1)
		{
			admin_product_redirect("error","Please enter a valid product ID using up to 5 letters or numbers.");
		}
		if($product_name==="" || strlen($product_name)>100 || $product_desc==="" || strlen($product_desc)>255)
		{
			admin_product_redirect("error","Please complete the product name and description within their character limits.");
		}
		if($product_price===false || $product_price<0.01 || $product_price>999.99 || $product_stock===false)
		{
			admin_product_redirect("error","Please enter a valid price and stock quantity.");
		}
		if(!in_array($product_status,array("Active","Inactive","Out of Stock"),true))
		{
			admin_product_redirect("error","Please select a valid product status.");
		}

		$category_stmt = mysqli_prepare($connect,"SELECT category_name FROM category WHERE category_name=? AND category_isDelete=0 LIMIT 1");
		if(!$category_stmt)
		{
			admin_product_redirect("error","The selected category could not be checked.");
		}
		mysqli_stmt_bind_param($category_stmt,"s",$product_category);
		mysqli_stmt_execute($category_stmt);
		$category_result = mysqli_stmt_get_result($category_stmt);
		$category_exists = mysqli_fetch_assoc($category_result)!==null;
		mysqli_stmt_close($category_stmt);
		if(!$category_exists)
		{
			admin_product_redirect("error","Please select an available category.");
		}

		$old_image = "";
		$uploaded_image = null;
		$transaction_started = false;
		try
		{
			if($mode==="update")
			{
				$current_stmt = mysqli_prepare($connect,"SELECT product_image FROM product WHERE product_id=? AND product_isDelete=0 LIMIT 1");
				if(!$current_stmt)
				{
					throw new RuntimeException("The product could not be loaded.");
				}
				mysqli_stmt_bind_param($current_stmt,"s",$product_id);
				mysqli_stmt_execute($current_stmt);
				$current_result = mysqli_stmt_get_result($current_stmt);
				$current_product = mysqli_fetch_assoc($current_result) ?: null;
				mysqli_stmt_close($current_stmt);
				if(!$current_product)
				{
					throw new RuntimeException("The selected product is unavailable.");
				}
				$old_image = (string)$current_product["product_image"];
			}

			$uploaded_image = admin_product_store_upload($_FILES["product_image"] ?? null,$product_id,$mode==="add");
			$product_image = $uploaded_image ?? $old_image;
			mysqli_begin_transaction($connect);
			$transaction_started = true;

			if($mode==="add")
			{
				$save_stmt = mysqli_prepare($connect,"INSERT INTO product(product_id,product_name,product_desc,product_image,product_category,product_price,product_stock,product_status,product_isDelete) VALUES(?,?,?,?,?,?,?,?,0)");
				if(!$save_stmt)
				{
					throw new RuntimeException("The product could not be prepared.");
				}
				mysqli_stmt_bind_param($save_stmt,"sssssdis",$product_id,$product_name,$product_desc,$product_image,$product_category,$product_price,$product_stock,$product_status);
			}
			else
			{
				$save_stmt = mysqli_prepare($connect,"UPDATE product SET product_name=?,product_desc=?,product_image=?,product_category=?,product_price=?,product_stock=?,product_status=? WHERE product_id=? AND product_isDelete=0");
				if(!$save_stmt)
				{
					throw new RuntimeException("The product could not be prepared.");
				}
				mysqli_stmt_bind_param($save_stmt,"ssssdiss",$product_name,$product_desc,$product_image,$product_category,$product_price,$product_stock,$product_status,$product_id);
			}

			if(!mysqli_stmt_execute($save_stmt))
			{
				throw new RuntimeException($mode==="add" ? "The product ID already exists." : "The product could not be updated.");
			}
			mysqli_stmt_close($save_stmt);
			mysqli_commit($connect);
			$transaction_started = false;

			if($uploaded_image!==null && $old_image!=="" && $old_image!==$uploaded_image)
			{
				admin_product_remove_generated_image($old_image);
			}
			admin_product_redirect("success",$mode==="add" ? "Product added successfully." : "Product updated successfully.");
		}
		catch(Throwable $error)
		{
			if($transaction_started)
			{
				mysqli_rollback($connect);
			}
			if($uploaded_image!==null)
			{
				admin_product_remove_generated_image($uploaded_image);
			}
			admin_product_redirect("error",$error->getMessage());
		}
	}

	if($action==="delete_product")
	{
		$product_id = strtoupper(trim((string)($_POST["product_id"] ?? "")));
		if(preg_match("/^[A-Z0-9]{1,5}$/",$product_id)!==1)
		{
			admin_product_redirect("error","Please select a valid product.");
		}

		mysqli_begin_transaction($connect);
		try
		{
			$image_stmt = mysqli_prepare($connect,"SELECT product_image FROM product WHERE product_id=? AND product_isDelete=0 FOR UPDATE");
			if(!$image_stmt)
			{
				throw new RuntimeException("The product could not be locked.");
			}
			mysqli_stmt_bind_param($image_stmt,"s",$product_id);
			mysqli_stmt_execute($image_stmt);
			$image_result = mysqli_stmt_get_result($image_stmt);
			$product_row = mysqli_fetch_assoc($image_result) ?: null;
			mysqli_stmt_close($image_stmt);
			if(!$product_row)
			{
				throw new RuntimeException("The selected product is unavailable.");
			}

			$delete_stmt = mysqli_prepare($connect,"UPDATE product SET product_isDelete=1,product_status='Inactive' WHERE product_id=? AND product_isDelete=0");
			if(!$delete_stmt)
			{
				throw new RuntimeException("The product could not be prepared for removal.");
			}
			mysqli_stmt_bind_param($delete_stmt,"s",$product_id);
			if(!mysqli_stmt_execute($delete_stmt) || mysqli_stmt_affected_rows($delete_stmt)!==1)
			{
				throw new RuntimeException("The selected product is unavailable.");
			}
			mysqli_stmt_close($delete_stmt);

			// Rewards linked to a removed product must no longer be redeemable.
			$reward_stmt = mysqli_prepare($connect,"UPDATE reward SET reward_status='Inactive' WHERE reward_product=? AND reward_isDelete=0");
			if(!$reward_stmt)
			{
				throw new RuntimeException("Linked rewards could not be updated.");
			}
			mysqli_stmt_bind_param($reward_stmt,"s",$product_id);
			if(!mysqli_stmt_execute($reward_stmt))
			{
				throw new RuntimeException("Linked rewards could not be updated.");
			}
			mysqli_stmt_close($reward_stmt);
			mysqli_commit($connect);
			// Keep the uploaded image while the record is soft-deleted so the
			// recycle bin can restore a complete product instead of a broken photo.
			admin_product_redirect("success","Product removed successfully.");
		}
		catch(Throwable $error)
		{
			mysqli_rollback($connect);
			admin_product_redirect("error",$error->getMessage());
		}
	}

	admin_product_redirect("error","The requested product action is not supported.");
}

