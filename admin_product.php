// Preview a selected local image and reject oversized files before submission.
const productImageInput = document.querySelector("[data-image-input]");
const productImagePreview = document.querySelector("[data-image-preview]");
if(productImageInput && productImagePreview)
{
	productImageInput.addEventListener("change",function()
	{
		const selectedFile = this.files && this.files[0] ? this.files[0] : null;
		if(!selectedFile)
		{
			return;
		}
		const acceptedTypes = ["image/jpeg","image/png","image/webp"];
		if(selectedFile.size>5*1024*1024 || !acceptedTypes.includes(selectedFile.type))
		{
			alert("Please choose a JPG, PNG or WebP image no larger than 5 MB.");
			this.value = "";
			return;
		}
		productImagePreview.src = URL.createObjectURL(selectedFile);
	});
}
